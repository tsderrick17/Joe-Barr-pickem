// Measures how much of its canvas each team logo actually fills and writes
// src/lib/team-logo-scale.js, so every logo shows at the same visual size.
//
//   node scripts/measure-team-logos.mjs
//
// The source images are all 500 x 500, but some marks (the Colts' horseshoe)
// run edge to edge while others sit in a wide transparent margin. A logo's
// size is the geometric mean of its inked width and height. Each logo is scaled
// toward the median size, within limits so no mark is distorted or cropped.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const directory = path.join(root, "public/team-logos");
const MIN_SCALE = 0.72;
const MAX_SCALE = 1.2;
// How strongly to correct: above 1 pulls the extremes in harder, because a mark
// that runs edge to edge reads larger than its measured area suggests.
const STRENGTH = 1.6;
const ALPHA_THRESHOLD = 24;

const files = (await readdir(directory)).filter((name) => name.endsWith(".png")).sort();
const sizes = {};
for (const file of files) {
  const { data, info } = await sharp(path.join(directory, file)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let minX = info.width, minY = info.height, maxX = -1, maxY = -1;
  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      if (data[(y * info.width + x) * info.channels + 3] > ALPHA_THRESHOLD) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  const inkWidth = (maxX - minX + 1) / info.width;
  const inkHeight = (maxY - minY + 1) / info.height;
  sizes[file.replace(/\.png$/, "")] = Math.sqrt(inkWidth * inkHeight);
}

const ordered = Object.values(sizes).sort((a, b) => a - b);
const median = ordered[Math.floor(ordered.length / 2)];
const scales = Object.fromEntries(Object.entries(sizes).map(([team, size]) => {
  const raw = (median / size) ** STRENGTH;
  return [team, Math.round(Math.min(MAX_SCALE, Math.max(MIN_SCALE, raw)) * 100) / 100];
}));

const body = Object.entries(scales).map(([team, scale]) => `  ${team}: ${scale.toFixed(2)},`).join("\n");
await writeFile(path.join(root, "src/lib/team-logo-scale.js"), `// Generated by scripts/measure-team-logos.mjs. Do not edit by hand.
// A multiplier for each team logo so its inked area reads at one consistent size.
export const TEAM_LOGO_SCALE = {
${body}
};

export function teamLogoScale(abbreviation) {
  return TEAM_LOGO_SCALE[String(abbreviation).trim().toUpperCase()] ?? 1;
}
`);
console.log(`Measured ${files.length} logos; median ink size ${median.toFixed(3)}.`);
console.log(Object.entries(scales).sort((a, b) => a[1] - b[1]).map(([team, scale]) => `${team} ${scale}`).join("  "));
